-- [weapon_fixed_mods] 특급 무기(44정)가 가진 고정 부품과 일부 일반/네임드 무기의 고정 부품.
--   출처: 부품 이름·효과는 나무위키 "톰 클랜시의 디비전 2/특급 장비" 각 무기 "부착물" 항목(한국어 원문 그대로).
--         어느 슬롯에 들어가는지는 Raigulus(div2hub/game-data, Y8S3)의 슬롯 정보와 나무위키의
--         [광학 레일]/[탄창 슬롯] 등 태그로 맞췄다. 나무위키와 Raigulus의 효과 수치가 다른 부품
--         (패치 차이)은 나무위키 수치를 썼다.
--   나무위키에 효과 수치가 없는 부품(탄환 제왕 "저장의 탄창")은 effect_ko를 빈 문자열로 둔다.
--   일반/네임드 고정 부품 중 "QDC 소음기"(Stoner LAMG, 소리 없는 아우성)와 "내장 조준경(8x)"(GR9, 담력, 크리켓)의
--   한국어 이름은 나무위키에 부품 이름이 없어("신속 탈착 결합부", "8배율 내장 조준경" 서술만 있음) 붙인 이름이고,
--   효과 수치는 Raigulus 값이다. 게임 화면과 다르면 name_ko만 고치면 된다.
--   특급 무기 중 "버티고(Vertigo)"는 나무위키에는 있으나 weapon_exotic에 없어 빠져 있다.

