  weapon_name_ko text not null,   -- weapon_models / weapon_named / weapon_exotic의 name_ko
  weapon_name_en text not null,
  slot text not null,             -- optic | magazine | underbarrel | muzzle
  name_ko text not null,
  effect_ko text not null default ''
);
alter table weapon_fixed_mods enable row level security;
create policy "public read" on weapon_fixed_mods for select using (true);

